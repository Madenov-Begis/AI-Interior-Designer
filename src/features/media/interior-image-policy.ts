export type InteriorImageDecision = "INTERIOR" | "NOT_INTERIOR";

export function parseInteriorImageDecision(
  value: string | undefined,
): InteriorImageDecision | null {
  const normalized = value?.trim().toUpperCase();
  if (normalized === "INTERIOR" || normalized === "NOT_INTERIOR") {
    return normalized;
  }
  return null;
}
